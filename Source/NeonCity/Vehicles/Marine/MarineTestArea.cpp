AMarineTestArea::AMarineTestArea()
{
 auto* Root=CreateDefaultSubobject<USceneComponent>(TEXT("Root")); SetRootComponent(Root);
 static ConstructorHelpers::FObjectFinder<UStaticMesh> Cube(TEXT("/Engine/BasicShapes/Cube.Cube"));
 auto Block=[&](FString Name,FVector Center,FVector Size)
 {
  auto* Mesh=CreateDefaultSubobject<UStaticMeshComponent>(*Name); Mesh->SetupAttachment(Root); Mesh->SetStaticMesh(Cube.Object);
  Mesh->SetRelativeLocation(Center); Mesh->SetRelativeScale3D(Size/100); Mesh->SetCollisionProfileName(TEXT("BlockAll"));
 };
 // Legacy isolated-world access. Authored mainland sites replace these fixtures.
 for(int32 I=0;I<6;++I)
 {
  const float Top=40+24*(I+1);
  Block(FString::Printf(TEXT("Approach%d"),I),FVector(5200,-1100-I*60,Top-15),FVector(400,60,30));
 }
 for(int32 I=0;I<11;++I)
 {
  const float Top=184-20*(I+1);
  Block(FString::Printf(TEXT("Descent%d"),I),FVector(5200,-1460-I*60,Top-15),FVector(400,60,30));
 }
 Block(TEXT("Pier"),FVector(5200,-2875,-58),FVector(400,1690,36));
 // Low submerged steps connect the existing pier to native swimming; no teleport/mantle logic.
 for(int32 I=0;I<8;++I) Block(FString::Printf(TEXT("WaterExit%d"),I),FVector(5200,-3750-I*60,-75-I*30),FVector(400,60,30));
 Block(TEXT("BerthFender"),FVector(5010,-3375,-135),FVector(30,600,210));
 Block(TEXT("BerthEnd"),FVector(4860,-2960,-80),FVector(280,80,110));
 for(int32 I=0;I<4;++I) Block(FString::Printf(TEXT("Pile%d"),I),FVector(5370,-2350-I*400,-230),FVector(30,30,360));
 auto* Sign=CreateDefaultSubobject<UTextRenderComponent>(TEXT("DockSign")); Sign->SetupAttachment(Root);
 Sign->SetRelativeLocation(FVector(5200,-1090,220)); Sign->SetRelativeRotation(FRotator(0,90,0));
 Sign->SetText(NSLOCTEXT("NeonCity","DockSign","SOUTH BEACH / MARINA\nSpeedboat berth / Harborline beyond the swim steps\nF board / take helm / leave helm   V camera\nSwim: WASD / Space up / C dive"));
 Sign->SetWorldSize(26); Sign->SetHorizontalAlignment(EHTA_Center);
}
void AMarineTestArea::PostInitializeComponents()
{
 Super::PostInitializeComponents();
 if(const auto* Site=ANeonCityMainlandSite::Find(GetWorld())) Site->ApplyLegacyTransportFixturePolicy(*this);
}
void AMarineTestArea::BeginPlay()
{
 Super::BeginPlay();
 const auto* Site=ANeonCityMainlandSite::Find(GetWorld());
 if(Site) Site->ApplyLegacyTransportFixturePolicy(*this);
 if(!HasAuthority()) return;
 const auto* Coast=ANeonCityCoastalRegion::Find(GetWorld());
 // The connected playable world uses the existing contextual interaction HUD.
 // Retain the old fixture helper only in isolated legacy development worlds.
 if(Coast) if(auto* Sign=FindComponentByClass<UTextRenderComponent>()) Sign->SetVisibility(false);
 if(Coast)
 {
  // Extend the existing provider into one continuous navigable coastal region.
  // Keep its sea datum and existing near-shore movement/physics contract.
  // Keep the existing south edge, X/Z envelope and sea datum. The authored
  // mainland's eastern headland extends north of the old -25m volume edge;
  // the same native ocean column must cover its coast, not only its renderer.
  // OceanSurface samples absolute world points, independent of this Y centre.
  // The south edge lies beyond the offshore island and moves with it (NeonCityCoastalLayout).
  const double SouthEdgeCm=-297500.+(NeonCityCoastalLayout::IslandOrigin.Y-NeonCityCoastalLayout::LegacyIslandOrigin.Y),NorthEdgeCm=35000.;
  const FTransform WaterTransform(FVector(0,(SouthEdgeCm+NorthEdgeCm)*.5,-20130));
  auto* Water=GetWorld()->SpawnActorDeferred<ANeonCityWaterVolume>(ANeonCityWaterVolume::StaticClass(),WaterTransform);
  if(Water)
  {
   const FTransform OceanTransform=FTransform::Identity;
   auto* Ocean=GetWorld()->SpawnActorDeferred<ACoastalOceanSurface>(ACoastalOceanSurface::StaticClass(),OceanTransform);
   if(Ocean)
   {
    // The persistent authored site owns configuration; this helper and its
    // provider are both generated by the existing world bootstrap at runtime.
    if(Site && Site->OceanField && !Ocean->InitializeField(Site->OceanField.Get(),Site->OceanRenderingMaterial.Get()))
     UE_LOG(LogTemp,Error,TEXT("Authored mainland ocean field rejected before BeginPlay; canonical field retained."));
    Ocean->FinishSpawning(OceanTransform);Fixtures.Add(Ocean);
   }
   Water->Extent=FVector(220000,(NorthEdgeCm-SouthEdgeCm)*.5,20000);Water->OceanSurface=Ocean;
   Water->FinishSpawning(WaterTransform);Fixtures.Add(Water);
  }
 }
 else Fixtures.Add(GetWorld()->SpawnActor<ANeonCityWaterVolume>(FVector(0,-14500,-2130),FRotator::ZeroRotator));
 const FTransform Transform=Site?Site->GetSpeedboatBerth():FTransform(FRotator(0,-90,0),FVector(4860,-3350,-134.5f));
 auto* Boat=GetWorld()->SpawnActorDeferred<ANeonCityMarineVehicleBase>(ANeonCityMarineVehicleBase::StaticClass(),Transform,nullptr,nullptr,ESpawnActorCollisionHandlingMethod::AlwaysSpawn);
 if(Boat)
 {
  Boat->VehicleID=UMarineWorldSubsystem::SpeedboatID();
  if(Site && Site->SpeedboatVisualMesh)
  {
   TInlineComponentArray<UStaticMeshComponent*> Visuals(Boat);
   for(auto* Visual:Visuals)if(Visual->GetFName()==TEXT("ArtVisual") && Visual->GetCollisionEnabled()==ECollisionEnabled::NoCollision)
   {Visual->SetStaticMesh(Site->SpeedboatVisualMesh.Get());Visual->EmptyOverrideMaterials();break;}
  }
  Boat->FinishSpawning(Transform);Fixtures.Add(Boat);
 }
 // Connected South Beach has one canonical island berth. The legacy coordinate
 // remains only for isolated worlds without an authored coastal region.
 const FTransform WorkingBerth=Coast?Coast->GetFishingBerth():FTransform(FRotator(0,-90,0),FVector(6000,-4700,-130));
 auto* WorkingBoat=GetWorld()->SpawnActorDeferred<ANeonCityFishingBoat>(ANeonCityFishingBoat::StaticClass(),WorkingBerth,nullptr,nullptr,ESpawnActorCollisionHandlingMethod::AlwaysSpawn);
 if(WorkingBoat) { WorkingBoat->VehicleID=UMarineWorldSubsystem::HarborlineID();WorkingBoat->GetMarineMovement()->SetMooringBerth(WorkingBerth);WorkingBoat->FinishSpawning(WorkingBerth);Fixtures.Add(WorkingBoat); }
}
void AMarineTestArea::EndPlay(EEndPlayReason::Type Reason)
{
 if(Reason==EEndPlayReason::Destroyed) for(auto Fixture:Fixtures) if(IsValid(Fixture)) Fixture->Destroy();
 Super::EndPlay(Reason);
}
